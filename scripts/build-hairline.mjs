// Bundles the Hairline kernel (hairline/kernel.js, vendored unchanged) and the About page's
// figures (hairline/<name>.js, written and checked with the hairline-create skill) into one
// module the site imports on the client: src/components/sections/hairline.generated.js.
// Run it after changing a figure: node scripts/build-hairline.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "hairline");
const out = join(import.meta.dirname, "..", "src", "components", "sections", "hairline.generated.js");
const names = readdirSync(dir).filter((f) => f.endsWith(".js") && f !== "kernel.js").sort();

const parts = [
  "/* eslint-disable */",
  "// Generated by scripts/build-hairline.mjs from hairline/*.js. Do not edit; edit the figures and run it again.",
  readFileSync(join(dir, "kernel.js"), "utf8"),
  "const figures = {};",
  // each figure ends by calling hairline(...): here that files it under its name
  "const hairline = (figure) => { figures[figure.name] = figure; };",
  ...names.map((f) => `// ${f}\n(() => {\n${readFileSync(join(dir, f), "utf8")}\n})();`),
  "export { HL, figures };",
];
writeFileSync(out, parts.join("\n") + "\n");
console.log(`wrote ${out} with ${names.length} figures: ${names.map((f) => f.replace(".js", "")).join(", ")}`);
